export function buildPlansForCluster(clusterId) {
  return GLOBAL_PLAN_TEMPLATES.map(t => {
    const cat = PLAN_CATALOG[t.baseId];
    return {
      id: planIdForCluster(clusterId, t.baseId),
      clusterId,
      name: t.name,
      kind: t.kind,
      method: t.method,
      connector: t.connector,
      playwrightPattern: PLAYWRIGHT_BY_BASE[t.baseId] || cat?.playwrightPattern || null,
      section: t.section,
      queries: [...t.queries],
      schedule: {
        enabled: false,
        frequency: 'daily',
        time: t.scheduleTime,
        dayOfWeek: 1,
        dayOfMonth: 1,
        lastFiredKey: null,
      },
      lastStatus: null,
      lastRunAt: null,
      lastResult: null,
    };
  });
}
